// Generates a static stand-in for the SPA's i18n resource registry.
//
// `src/i18n/resources.ts` discovers locale catalogs with `import.meta.glob`,
// which is a VITE feature. The design-sync converter bundles with esbuild in
// IIFE format, where `import.meta` is `{}` — so the module throws
// `import_meta.glob is not a function` at load and takes every component in
// the bundle down with it (all 35 previews rendered empty).
//
// Rather than change the app's i18n (the glob is a deliberate ergonomic: drop
// a JSON file, no edits needed), this emits an equivalent module with static
// imports and the same public surface. `.design-sync/tsconfig.paths.json`
// redirects the `./resources` specifier onto it for the converter's bundle
// only; the SPA build is untouched.
//
// Regenerate whenever a locale or namespace is added — `buildCmd` does it.
// Run from the repo root: node .design-sync/gen-i18n-resources.mjs

import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LOCALES_DIR = "packages/workout-spa-editor/src/i18n/locales";
const IMPORT_PREFIX = "../packages/workout-spa-editor/src/i18n/locales";
const OUT = ".design-sync/i18n-resources-static.ts";

/** `labs-ui` -> `labs_ui`, so the namespace can be a JS identifier. */
const ident = (locale, ns) => `${locale}_${ns}`.replace(/[^A-Za-z0-9_]/g, "_");

const locales = readdirSync(LOCALES_DIR, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const imports = [];
const catalogs = [];

for (const locale of locales) {
  const namespaces = readdirSync(join(LOCALES_DIR, locale))
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.slice(0, -".json".length))
    .sort();
  for (const ns of namespaces) {
    imports.push(
      `import ${ident(locale, ns)} from "${IMPORT_PREFIX}/${locale}/${ns}.json";`
    );
  }
  const entries = namespaces
    .map((ns) => `    ${JSON.stringify(ns)}: ${ident(locale, ns)},`)
    .join("\n");
  catalogs.push(`  ${JSON.stringify(locale)}: {\n${entries}\n  },`);
}

const source = `// GENERATED by .design-sync/gen-i18n-resources.mjs - do not edit by hand.
//
// Static equivalent of packages/workout-spa-editor/src/i18n/resources.ts for
// the design-sync bundle. The original discovers catalogs with Vite's
// \`import.meta.glob\`, which esbuild cannot provide; the exported surface here
// is identical, so the components render the same strings the storybook
// reference renders.

import type { Locale, LocaleNamespaces } from "@kaiord/i18n";

${imports.join("\n")}

const CATALOGS: Record<string, LocaleNamespaces> = {
${catalogs.join("\n")}
};

export const DEFAULT_NAMESPACE = "common";

/** The English catalog: i18next's fallback and the default render language. */
export const DEFAULT_CATALOG: LocaleNamespaces = CATALOGS["en"] ?? {};

export const NAMESPACES = Object.keys(DEFAULT_CATALOG);

export const getLocaleNamespaces = (
  locale: Locale
): LocaleNamespaces | undefined => CATALOGS[locale];

/** Every catalog is bundled here, so this resolves without a network round. */
export const loadLocaleNamespaces = async (
  locale: Locale
): Promise<LocaleNamespaces> => CATALOGS[locale] ?? DEFAULT_CATALOG;
`;

writeFileSync(OUT, source);
console.log(
  `wrote ${OUT}: ${locales.length} locale(s), ${imports.length} catalog file(s)`
);
